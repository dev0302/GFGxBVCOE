const FALLBACK_WIDTH = HANDWRITING_FONT[" "].w;

/**
 * Parse a glyph's raw "d" (a chain of M/L commands, y-up, in its own local
 * box) into subpaths of plain [x, y] points. A new subpath starts at every
 * M — most letters are one continuous subpath, a few (like the tail on "o")
 * lift the pen for a second short stroke.
 */
function parseSubpaths(rawD) {
  const tokens = rawD.replace(/,/g, " ").trim().split(/\s+/);
  let currentCmd = null;
  let firstPointDone = false;
  const buffer = [];
  const subpaths = [];
  let current = null;

  const pushPoint = (isMove) => {
    const point = [parseFloat(buffer[0]), parseFloat(buffer[1])];
    if (isMove) {
      current = [point];
      subpaths.push(current);
    } else {
      current.push(point);
    }
    buffer.length = 0;
  };

  tokens.forEach((token) => {
    if (/^[MLZmlz]$/.test(token)) {
      currentCmd = token.toUpperCase();
      firstPointDone = false;
      return;
    }
    buffer.push(token);
    if (buffer.length === 2) {
      if (currentCmd === "M" && !firstPointDone) {
        pushPoint(true);
        firstPointDone = true;
      } else {
        pushPoint(false);
      }
    }
  });

  return subpaths;
}

/**
 * Fit a smooth cubic-bezier curve through a chain of points using a clamped
 * Catmull-Rom spline. This is what turns the font's raw polyline data (lots
 * of short straight segments) into the flowing, continuous curves a real
 * pen would make — straight lines simply don't read as handwriting.
 */
function smoothPointsToPath(points) {
  const [first] = points;
  let d = `M${first[0].toFixed(1)},${first[1].toFixed(1)} `;

  if (points.length === 2) {
    return d + `L${points[1][0].toFixed(1)},${points[1][1].toFixed(1)}`;
  }

  const segments = [];
  for (let i = 0; i < points.length - 1; i++) {
    const p0 = points[i - 1] || points[i];
    const p1 = points[i];
    const p2 = points[i + 1];
    const p3 = points[i + 2] || p2;
    const c1x = p1[0] + (p2[0] - p0[0]) / 6;
    const c1y = p1[1] + (p2[1] - p0[1]) / 6;
    const c2x = p2[0] - (p3[0] - p1[0]) / 6;
    const c2y = p2[1] - (p3[1] - p1[1]) / 6;
    segments.push(
      `C${c1x.toFixed(1)},${c1y.toFixed(1)} ${c2x.toFixed(1)},${c2y.toFixed(1)} ${p2[0].toFixed(1)},${p2[1].toFixed(1)}`
    );
  }
  return d + segments.join(" ");
}

/**
 * Turn a glyph's raw "d" into an absolute, smoothed path fragment placed at
 * `offsetX` along the shared baseline, flipped to the usual y-down SVG
 * convention. The result has no <transform> of its own, so
 * getTotalLength()/getPointAtLength() on the rendered <path> map directly
 * to on-screen position.
 */
function bakeGlyphPath(rawD, offsetX) {
  const subpaths = parseSubpaths(rawD);
  const placed = subpaths.map((sp) => sp.map(([x, y]) => [x + offsetX, UNITS_PER_EM - y]));
  return placed.map(smoothPointsToPath).join(" ");
}

/**
 * Build the list of stroke paths (one per visible glyph) needed to write
 * `text` in order, plus a tight viewBox that frames the whole phrase.
 *
 * @param {string} text - e.g. "Hello" or "Hello, Alex"
 * @param {number} pad - extra breathing room around the glyphs, in font units
 * @returns {{
 *   strokes: { char: string, d: string, isWordStart: boolean }[],
 *   viewBox: string,
 *   width: number,
 *   height: number,
 * }}
 */
export function buildHandwritingWord(text, pad = 70) {
  const words = String(text ?? "").split(" ").filter((w) => w.length > 0);
  const strokes = [];
  let offsetX = 0;
  let minX = Infinity;
  let minY = Infinity;
  let maxX = -Infinity;
  let maxY = -Infinity;

  const trackBounds = (d) => {
    // Matches every x,y pair in the path (M points, and C control/end
    // points). Bezier control points can sit slightly outside the curve's
    // true extent, so this slightly over-estimates the box — harmless given
    // the padding already applied below.
    const re = /(-?\d+\.?\d*),(-?\d+\.?\d*)/g;
    let match;
    // eslint-disable-next-line no-cond-assign
    while ((match = re.exec(d))) {
      const x = parseFloat(match[1]);
      const y = parseFloat(match[2]);
      if (x < minX) minX = x;
      if (x > maxX) maxX = x;
      if (y < minY) minY = y;
      if (y > maxY) maxY = y;
    }
  };

  words.forEach((word, wordIndex) => {
    if (wordIndex > 0) {
      offsetX += HANDWRITING_FONT[" "].w;
    }
    Array.from(word).forEach((ch, charIndex) => {
      const glyph = HANDWRITING_FONT[ch];
      if (!glyph) {
        offsetX += FALLBACK_WIDTH;
        return;
      }
      if (glyph.d) {
        const d = bakeGlyphPath(glyph.d, offsetX);
        trackBounds(d);
        strokes.push({
          char: ch,
          d,
          isWordStart: wordIndex > 0 && charIndex === 0,
        });
      }
      offsetX += glyph.w;
    });
  });

  if (!Number.isFinite(minX)) {
    // Nothing renderable (e.g. empty string) — return an empty, harmless result.
    return { strokes: [], viewBox: "0 0 100 100", width: 100, height: 100 };
  }

  const width = maxX - minX + pad * 2;
  const height = maxY - minY + pad * 2;
  const viewBox = `${minX - pad} ${minY - pad} ${width} ${height}`;

  return { strokes, viewBox, width, height };
}
